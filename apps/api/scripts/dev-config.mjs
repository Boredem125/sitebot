// Writes wrangler.dev.jsonc: the production config with the Vectorize index swapped for the
// dev one. Vectorize has no local simulator, so without this `wrangler dev` would read and
// write the vectors that production answers from.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROD_INDEX = '"index_name": "sitebot-chunks"';
const DEV_INDEX = '"index_name": "sitebot-chunks-dev"';
const HEADER = '// GENERATED by scripts/dev-config.mjs from wrangler.jsonc. Do not edit: changes are overwritten.\n';

const apiDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = join(apiDir, 'wrangler.jsonc');
const targetPath = join(apiDir, 'wrangler.dev.jsonc');

// Handled as text: the file is JSONC, with comments and with `//` inside URL strings.
const source = readFileSync(sourcePath, 'utf8');
const found = source.split(PROD_INDEX).length - 1;
if (found !== 1) {
  // Starting the dev server anyway would point it at whatever index the config names.
  console.error(
    `dev-config: expected ${PROD_INDEX} exactly once in wrangler.jsonc, found it ${found} times. ` +
      'wrangler.dev.jsonc was not written.',
  );
  process.exit(1);
}

writeFileSync(targetPath, HEADER + source.replace(PROD_INDEX, DEV_INDEX));
console.log('dev-config: wrote wrangler.dev.jsonc (Vectorize index sitebot-chunks-dev)');
